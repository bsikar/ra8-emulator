pub fn findEntry(group: []const u8) ?Entry {
    for (entries) |entry| {
        if (std.mem.eql(u8, entry.group, group)) return entry;
    }
    return null;
}

pub fn find(group: []const u8) ?Print {
    return if (findEntry(group)) |entry| entry.print else null;
}
